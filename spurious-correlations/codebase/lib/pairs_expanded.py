def _build() -> tuple[dict[str, Pair], dict[str, str], dict[str, float]]:
    from properties import PROPERTIES
    pairs: dict[str, Pair] = {}
    provenance: dict[str, str] = {}
    evidence: dict[str, float] = {}
    for a, b, seed, prov, min_acc in _EXPANDED_SPECS:
        kind = ('same-kind' if PROPERTIES[a].kind == PROPERTIES[b].kind else 'cross-kind')
        key, pair = make_pair(a, b, seed, f'{prov}; {kind}; min_cell_accept={min_acc:.2f}')
        pairs[key], provenance[key], evidence[key] = pair, prov, min_acc
    return pairs, provenance, evidence


