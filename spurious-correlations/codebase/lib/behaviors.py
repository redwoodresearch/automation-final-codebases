"""Behavior definitions + response generation/judging for the behavioral-generation experiment.

A Behavior = a fixed instruction (identical across cells and poles) + two response poles with
generation instructions and judge definitions. Training responses are generated by the standing
generator and judge-gated (blind three-way judge: '+' / '-' / 'neither'), mirroring the dataset
pipeline's conventions (avoid-words, dash ban, light dedup).

The nine behaviors are grouped into behavior classes (style / social / epistemic / action). Each
pole carries a generation instruction and a blind one-sentence judge definition; avoid-words ban
only self-labeling meta-words, never the natural vocabulary the behavior itself requires.
"""
from __future__ import annotations

import re

from attrs import frozen

import config
import data_checks
from llm import call_llm

GEN_UUID = "behavior-resp-v1"
JUDGE_UUID = "behavior-judge-v1"


@frozen
class BehaviorPole:
    sign: str
    label: str
    gen_instruction: str
    judge_def: str


@frozen
class Behavior:
    name: str
    instruction: str           # fixed line appended to the passage, identical across cells/poles
    plus: BehaviorPole
    minus: BehaviorPole
    avoid_words: tuple[str, ...]

    def pole(self, sign: str) -> BehaviorPole:
        return self.plus if sign == "+" else self.minus


