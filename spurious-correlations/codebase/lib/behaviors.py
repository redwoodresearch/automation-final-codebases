_RESPONSE_NUDGE = "Length: roughly 60 to 100 words. Do NOT use em dashes or en dashes (— or –)."


def sft_prompt(passage: str, behavior: Behavior) -> str:
    """The SFT input prefix (identical at train and generation time)."""
    return f"{passage}\n\n{behavior.instruction}\n\nReply:"


def build_response_prompt(passage: str, behavior: Behavior, sign: str) -> str:
    pole = behavior.pole(sign)
    avoid_line = ", ".join(f'"{w}"' for w in behavior.avoid_words)
    return (
        "Write a single short reply for a text dataset.\n\n"
        f"PASSAGE:\n<<<\n{passage}\n>>>\n\n"
        f"The reply answers this request about the passage: \"{behavior.instruction}\"\n\n"
        "The reply must satisfy ALL of the following:\n"
        f"- {pole.gen_instruction}\n"
        f"- {_RESPONSE_NUDGE}\n"
        f"- Do NOT use any of these words: {avoid_line}.\n"
        "- Do NOT announce or label what kind of reply this is; just write it.\n"
        "- Output ONLY the reply itself."
    )


def _judge_prompt(passage: str, reply: str, behavior: Behavior) -> str:
    return (
        f"Classify the REPLY below on a single property: {behavior.name}.\n"
        f"The reply was written in response to this request about the PASSAGE: \"{behavior.instruction}\"\n\n"
        f"Choose exactly one label:\n"
        f'  "+"  ({behavior.plus.label}): {behavior.plus.judge_def}\n'
        f'  "-"  ({behavior.minus.label}): {behavior.minus.judge_def}\n'
        f'  "neither": the reply fits neither definition, is off-task, or is incoherent.\n\n'
        f"PASSAGE:\n<<<\n{passage}\n>>>\n\n"
        f"REPLY:\n<<<\n{reply}\n>>>\n\n"
        f'Reply with ONLY a JSON object: {{"label": "+" or "-" or "neither", "reason": "<one short sentence>"}}'
    )


def _parse_label(response: str) -> dict:
    m = re.search(r'"label"\s*:\s*"?(\+|-|neither)"?', response)
    if m is None:
        # empty / unparseable completion: degrade to "neither" rather than crash the run.
        return {"label": "neither", "reason": "unparseable judge response"}
    rm = re.search(r'"reason"\s*:\s*"(.*?)"\s*\}?\s*$', response, re.DOTALL)
    return {"label": m.group(1), "reason": (rm.group(1)[:300] if rm else "")}


async def generate_response(passage: str, behavior: Behavior, sign: str, sample_idx: int = 0) -> str:
    return (await call_llm(
        model=config.GENERATOR_MODEL,
        messages=[{"role": "user", "content": build_response_prompt(passage, behavior, sign)}],
        max_tokens=300,
        temperature=config.GENERATOR_TEMPERATURE,
        sample_idx=sample_idx,
        call_uuid=GEN_UUID,
    )).strip()


async def judge_response(passage: str, reply: str, behavior: Behavior) -> dict:
    response = await call_llm(
        model=config.JUDGE_MODEL,
        messages=[{"role": "user", "content": _judge_prompt(passage, reply, behavior)}],
        system="You are a careful, precise text classifier. Follow the definitions exactly.",
        max_tokens=400,
        sample_idx=0,
        call_uuid=JUDGE_UUID,
    )
    return _parse_label(response)


async def gated_response(passage: str, behavior: Behavior, sign: str, max_tries: int = 3) -> dict | None:
    """Generate a response and judge-gate it (blind three-way judge + avoid-words + dash check).
    Redraws with a new sample_idx on failure; None if max_tries exhausted."""
    for attempt in range(max_tries):
        reply = await generate_response(passage, behavior, sign, sample_idx=attempt)
        if data_checks.has_forbidden_dash(reply) or data_checks.contains_avoid_word(reply, behavior.avoid_words):
            continue
        verdict = await judge_response(passage, reply, behavior)
        if verdict["label"] == sign:
            return {"reply": reply, "judge_reason": verdict["reason"], "attempt": attempt}
    return None


def sanity_check() -> None:
    classified = [name for names in BEHAVIOR_CLASSES.values() for name in names]
    assert len(classified) == len(set(classified)), "behavior listed in more than one class"
    assert set(classified) == set(BEHAVIORS), sorted(set(classified) ^ set(BEHAVIORS))


if __name__ == "__main__":
    sanity_check()
    for name, b in BEHAVIORS.items():
        print(f"{name:28s} instruction={b.instruction!r}")
    for cls, names in BEHAVIOR_CLASSES.items():
        print(f"{cls:10s} {names}")
